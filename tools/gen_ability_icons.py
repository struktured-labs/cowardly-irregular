# debuff is buff upside down: the same arrow, pointing the other way.
MASKS["debuff"] = list(reversed(MASKS["buff"]))
# Shared with the item set on purpose, so the two sets agree on what these look like.
MASKS["strike"] = ITEM_MASKS["sword"]
MASKS["lightning"] = ITEM_MASKS["bolt"]
MASKS["phoenix"] = ITEM_MASKS["phoenix"]
MASKS["ether"] = ITEM_MASKS["ether"]


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    images = {}
    for key, mask in MASKS.items():
        if len(mask) != SIZE:
            raise SystemExit("%s has %d rows" % (key, len(mask)))
        images[key] = render(mask, [])
        write_png(OUT / ("%s.png" % key), images[key])
    sheet, _w, _h = contact_sheet(images)
    Path("tmp").mkdir(exist_ok=True)
    write_sheet(Path("tmp/ability_icon_sheet.png"), sheet)
    print("wrote %d icons to %s" % (len(images), OUT))


if __name__ == "__main__":
    main()
