def _blank():
    return [[(0, 0, 0, 0) for _ in range(SIZE)] for _ in range(SIZE)]


def render(mask, details):
    im = _blank()
    filled = []
    for y, row in enumerate(mask):
        if len(row) != SIZE:
            raise SystemExit("row %d len %d" % (y, len(row)))
        for x, ch in enumerate(row):
            if ch == "#":
                im[y][x] = (255, 255, 255, 255)
                filled.append((x, y))
    if filled:
        ys = [y for _x, y in filled]
        ymin, ymax = min(ys), max(ys)
        span = max(1, ymax - ymin)
        for x, y in filled:
            if (y - ymin) / span >= 0.62:
                im[y][x] = (150, 150, 150, 255)
    # Collect first. Writing outline during the scan makes each new black pixel
    # recruit the pixel beside it, and the outline floods to the tile edge.
    outline = []
    for y in range(SIZE):
        for x in range(SIZE):
            if im[y][x][3] != 0:
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                nx, ny = x + dx, y + dy
                if 0 <= nx < SIZE and 0 <= ny < SIZE and im[ny][nx][3] != 0:
                    outline.append((x, y))
                    break
    for x, y in outline:
        im[y][x] = (0, 0, 0, 255)
    for x, y in details:
        if im[y][x][3] != 0 and im[y][x] != (0, 0, 0, 255):
            im[y][x] = (0, 0, 0, 255)
    return im


def write_png(path, im):
    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    raw = b"".join(b"\x00" + b"".join(bytes(px) for px in row) for row in im)
    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", struct.pack(">IIBBBBB", SIZE, SIZE, 8, 6, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(raw, 9))
    png += chunk(b"IEND", b"")
    path.write_bytes(png)


def contact_sheet(images):
    keys = sorted(images)
    cols = 8
    rows = (len(keys) + cols - 1) // cols
    pad = 2
    cell = SIZE + pad
    w, h = cols * cell + pad, rows * cell + pad
    sheet = [[(20, 16, 32, 255) for _ in range(w)] for _ in range(h)]
    for i, key in enumerate(keys):
        ox = pad + (i % cols) * cell
        oy = pad + (i // cols) * cell
        im = images[key]
        for y in range(SIZE):
            for x in range(SIZE):
                px = im[y][x]
                if px[3] == 0:
                    continue
                # Preview tint so the sheet is readable: a warm red multiply.
                if px == (0, 0, 0, 255):
                    sheet[oy + y][ox + x] = px
                else:
                    sheet[oy + y][ox + x] = (
                        int(px[0] * 0.95),
                        int(px[1] * 0.35),
                        int(px[2] * 0.32),
                        255,
                    )
    return sheet, w, h


def write_sheet(path, sheet):
    h = len(sheet)
    w = len(sheet[0])

    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    raw = b"".join(b"\x00" + b"".join(bytes(px) for px in row) for row in sheet)
    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(raw, 9))
    png += chunk(b"IEND", b"")
    path.write_bytes(png)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    images = {}
    for key, mask in MASKS.items():
        if len(mask) != SIZE:
            raise SystemExit("%s has %d rows" % (key, len(mask)))
        im = render(mask, DETAILS.get(key, []))
        images[key] = im
        write_png(OUT / ("%s.png" % key), im)
    sheet, _w, _h = contact_sheet(images)
    write_sheet(Path("tmp/item_icon_sheet.png"), sheet)
    print("wrote %d icons to %s" % (len(images), OUT))


if __name__ == "__main__":
    main()
